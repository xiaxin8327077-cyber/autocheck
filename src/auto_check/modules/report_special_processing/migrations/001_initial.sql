CREATE TABLE report_special_processing_reports (
    id BIGINT NOT NULL AUTO_INCREMENT,
    record_id BIGINT NOT NULL,
    sequence_no INT NOT NULL,
    report_name VARCHAR(200) NOT NULL,
    report_name_normalized VARCHAR(200) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_rsp_reports_sequence (record_id, sequence_no),
    UNIQUE KEY uq_rsp_reports_name (record_id, report_name_normalized),
    KEY ix_rsp_reports_record (record_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
