CREATE TABLE report_special_processing_audit_logs (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '审计日志主键',
    record_id BIGINT NOT NULL COMMENT '关联特殊处理记录主键',
    record_no_snapshot VARCHAR(32) NOT NULL COMMENT '特殊处理记录编号快照',
    action_code VARCHAR(32) NOT NULL COMMENT '操作类型编码',
    operator_user_id VARCHAR(64) NOT NULL COMMENT '操作人用户 ID',
    operator_username_snapshot VARCHAR(100) NOT NULL COMMENT '操作人用户名快照',
    operator_display_name_snapshot VARCHAR(100) NOT NULL COMMENT '操作人显示名称快照',
    occurred_at DATETIME(6) NOT NULL COMMENT '操作发生时间',
    from_status VARCHAR(20) NULL COMMENT '操作前处理状态',
    to_status VARCHAR(20) NULL COMMENT '操作后处理状态',
    changed_fields_json TEXT NOT NULL COMMENT '变更字段 JSON',
    action_summary VARCHAR(1000) NOT NULL COMMENT '操作摘要',
    request_id VARCHAR(64) NULL COMMENT '请求追踪 ID',
    PRIMARY KEY (id),
    KEY ix_rsp_audit_record_time (record_id, occurred_at),
    KEY ix_rsp_audit_operator_time (operator_user_id, occurred_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='报表特殊处理操作审计日志表'
