CREATE TABLE report_special_processing_audit_logs (
    id BIGINT NOT NULL AUTO_INCREMENT,
    record_id BIGINT NOT NULL,
    record_no_snapshot VARCHAR(32) NOT NULL,
    action_code VARCHAR(32) NOT NULL,
    operator_user_id VARCHAR(64) NOT NULL,
    operator_username_snapshot VARCHAR(100) NOT NULL,
    operator_display_name_snapshot VARCHAR(100) NOT NULL,
    occurred_at DATETIME(6) NOT NULL,
    from_status VARCHAR(20) NULL,
    to_status VARCHAR(20) NULL,
    changed_fields_json TEXT NOT NULL,
    action_summary VARCHAR(1000) NOT NULL,
    request_id VARCHAR(64) NULL,
    PRIMARY KEY (id),
    KEY ix_rsp_audit_record_time (record_id, occurred_at),
    KEY ix_rsp_audit_operator_time (operator_user_id, occurred_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
