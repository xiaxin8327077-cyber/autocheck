CREATE TABLE report_special_processing_reports (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '涉及报表明细主键',
    record_id BIGINT NOT NULL COMMENT '关联特殊处理记录主键',
    sequence_no INT NOT NULL COMMENT '报表显示顺序',
    report_name VARCHAR(200) NOT NULL COMMENT '报表名称',
    report_name_normalized VARCHAR(200) NOT NULL COMMENT '用于去重匹配的规范化报表名称',
    created_at DATETIME(6) NOT NULL COMMENT '创建时间',
    PRIMARY KEY (id),
    UNIQUE KEY uq_rsp_reports_sequence (record_id, sequence_no),
    UNIQUE KEY uq_rsp_reports_name (record_id, report_name_normalized),
    KEY ix_rsp_reports_record (record_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='报表特殊处理涉及报表明细表'
