import assert from "node:assert/strict";
import { FakeElement, collectByClass, collectText, findButton } from "./frontend_workbench_dom.mjs";
import { openSqlTestDialog, previousMonthEnd } from "./components/sql_test_dialog.mjs";

assert.equal(previousMonthEnd(new Date(2026, 0, 15)), "2025-12-31");
assert.equal(previousMonthEnd(new Date(2024, 2, 1)), "2024-02-29");
assert.equal(previousMonthEnd(new Date(2026, 10, 20)), "2026-10-31");
const host = new FakeElement("div");
let requests = [];
let signals = [];
const preview = { definition: { source_id: "src" }, content_sha256: "hash" };
const api = { runCandidateSql: async (payload, { signal }) => {
  requests.push(payload); signals.push(signal);
  return { columns: [{ name: "项目编号" }, { name: "余额" }],
    rows: [{ values: { 项目编号: "001", 余额: 0 } }, { values: { 项目编号: "002", 余额: null } }],
    row_count: 2, truncated: false };
} };
const dialog = openSqlTestDialog({ host, api, preview, now: new Date(2026, 10, 20) });
await dialog.ready;
assert.equal(requests.length, 1);
assert.equal(requests[0].report_date, "2026-10-31");
assert.equal(requests[0].expected_hash, "hash");
assert.ok(collectText(dialog.body).includes("001"));
assert.ok(collectText(dialog.body).includes("NULL"));
assert.equal(collectByClass(dialog.body, "dv-sql-test-table")[0].children[1].children.length, 2);
assert.ok(collectText(dialog.body).includes("2 条"));
assert.equal(collectByClass(dialog.body, "dv-sql-test-state")[0].hidden, true);
assert.equal(collectByClass(dialog.body, "dv-sql-test-table-wrap")[0].hidden, false);
assert.ok(collectText(dialog.body).includes("运行完成"));
await dialog.element.dispatch("click");
assert.equal(dialog.isClosed(), false, "点击遮罩不关闭二级弹窗");
const date = collectByClass(dialog.body, "dv-sql-test-date")[0];
date.value = "2026-09-30";
await date.dispatch("change");
assert.equal(collectByClass(dialog.body, "dv-sql-test-table-wrap")[0].hidden, true);
assert.ok(collectText(dialog.body).includes("报送日期已修改"));
date.value = "";
await findButton(dialog.body, "重新运行").dispatch("click");
assert.equal(requests.length, 1);
date.value = "2026-09-30";
api.runCandidateSql = async () => ({ columns: [{ name: "项目编号" }], rows: [], row_count: 0, truncated: false });
await findButton(dialog.body, "重新运行").dispatch("click");
assert.ok(collectText(dialog.body).includes("未查询到异常数据"));
assert.equal(collectByClass(dialog.body, "dv-sql-test-table-wrap")[0].hidden, true, "零行结果不保留空表头和横向滚动条");
assert.equal(collectByClass(dialog.body, "dv-sql-test-state")[0].hidden, false);
assert.ok(collectText(dialog.body).includes("2026-09-30"), "空结果说明所查询的报送日期");
api.runCandidateSql = async () => { throw { code: "TIMEOUT" }; };
await findButton(dialog.body, "重新运行").dispatch("click");
assert.ok(collectText(dialog.body).includes("超时"));
assert.ok(!collectText(dialog.body).includes("未查询到异常数据"));
assert.equal(collectByClass(dialog.body, "dv-sql-test-table-wrap")[0].hidden, true);
assert.ok(collectText(dialog.body).includes("运行失败"));
dialog.close();
assert.ok(signals[0].aborted);
assert.equal(host.children.length, 0);

let resolve;
api.runCandidateSql = (_payload, { signal }) => { signals.push(signal); return new Promise(r => { resolve = r; }); };
const pending = openSqlTestDialog({ host, api, preview });
assert.ok(findButton(pending.body, "运行中…").disabled);
assert.equal(pending.body.getAttribute("aria-busy"), "true");
assert.equal(collectByClass(pending.body, "dv-sql-test-state")[0].hidden, false);
pending.close();
resolve({ columns: [], rows: [], row_count: 0 });
await pending.ready;
assert.equal(host.children.length, 0, "关闭后迟到响应不能恢复弹窗");
assert.ok(signals.at(-1).aborted);

const parent = new FakeElement("section");
const originalFocus = new FakeElement("button");
originalFocus.isConnected = true;
parent.append(originalFocus); host.append(parent); originalFocus.focus();
api.runCandidateSql = async () => ({ columns: [], rows: [], row_count: 0 });
const nested = openSqlTestDialog({ host, api, preview, parent });
await nested.ready;
assert.equal(parent.inert, true);
await nested.dialog.dispatch("keydown", { key: "Tab", shiftKey: true });
assert.equal(document.activeElement, findButton(nested.footer, "关闭"));
await nested.dialog.dispatch("keydown", { key: "Tab" });
assert.equal(document.activeElement, nested.closeButton);
nested.close();
assert.equal(Boolean(parent.inert), false);
assert.equal(document.activeElement, originalFocus);
console.log("SQL test dialog behavior passed");
