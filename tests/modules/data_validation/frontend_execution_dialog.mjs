import assert from "node:assert/strict";
import { FakeElement, collectByClass, collectText, controlByLabel, findButton } from "./frontend_workbench_dom.mjs";
import { createState } from "./state.mjs";
import { createRuntime } from "./runtime.mjs";
import { openTaskDialog } from "./components/task_dialog.mjs";
const runtime = createRuntime({ notify() {} }); runtime.activate();
const state = createState(); state.reportPeriod = "2026-10-31"; state.sources = [{ id: "s1", name: "监管报表" }, { id: "s2", name: "报送集市" }];
const rules = [1, 2, 3].map((id) => ({ id, rule_code: `DV${id}`, name: `校验${id}`, source_id: id === 3 ? "s2" : "s1", table_name: "proj_info", table_name_cn: "项目信息（proj_info.ktr）", status: "enabled" }));
const requests = []; let saved; let started; const host = new FakeElement("div");
const api = { rules: async (query) => { requests.push(query); const items = query.source_id ? rules.filter((rule) => rule.source_id === query.source_id) : rules.slice(0, 2); return { items, total: 3, page: 1, page_size: 20 }; }, startTask: async (payload) => { saved = payload; return { id: 1, report_period: payload.report_period }; } };
const dialog = openTaskDialog({ state, runtime, api, host, notify() {}, initialRules: [rules[0]], onStarted: (task) => { started = task; } });
await new Promise((resolve) => setTimeout(resolve, 0));
assert.match(collectText(dialog.dialog), /执行校验/);
assert.ok(controlByLabel(dialog.body, "数据源"));
assert.match(collectText(dialog.body), /项目信息（proj_info）/); assert.doesNotMatch(collectText(dialog.body), /\.ktr|s1 \/|status=enabled/);
const selectAll = collectByClass(dialog.body, "dv-rule-checkbox").find((box) => box.getAttribute("aria-label") === "选择当前页全部已启用规则");
assert.ok(selectAll); assert.equal(selectAll.indeterminate, true);
selectAll.checked = true; await selectAll.dispatch("change");
assert.match(collectText(dialog.footer), /已选 2 条规则 · 将生成 1 个执行批次/);
const source = controlByLabel(dialog.body, "数据源"); source.value = "s2"; await source.dispatch("change");
await new Promise((resolve) => setTimeout(resolve, 0));
assert.equal(requests.at(-1).source_id, "s2"); assert.equal(requests.at(-1).page, 1);
assert.match(collectText(dialog.footer), /已选 2 条规则/);
const third = collectByClass(dialog.body, "dv-rule-checkbox").find((box) => box.dataset.enabledRule === "3");
third.checked = true; await third.dispatch("change");
// 误点遮罩或 Esc 不关闭。
await dialog.element.dispatch("click"); await dialog.element.dispatch("keydown", { key: "Escape" }); assert.equal(dialog.isClosed(), false);
await findButton(dialog.footer, "开始执行（3条）").dispatch("click");
assert.deepEqual(saved, { rule_ids: [1, 2, 3], source_id: "", report_period: "2026-10-31" });
assert.equal(started.id, 1); assert.equal(dialog.isClosed(), true);
runtime.destroy(); console.log(JSON.stringify({ ok: true }));
